const SKIP_CITY_NAMES = new Set(['市辖区', '省直辖县级行政区划', '直辖县级']);

export interface ChinaRegionPath {
  province: string;
  city: string | null;
  district: string | null;
  /** 展示标签:跳过「市辖区」等噪声级,如「上海市 黄浦区」 */
  label: string;
  lat: number;
  lon: number;
}

export function regionLabel(province: string, city: string | null, district: string | null): string {
  return [province, city !== null && !SKIP_CITY_NAMES.has(city) ? city : '', district ?? '']
    .filter(Boolean)
    .join(' ');
}

/** 由经纬度反查省市区路径(取曼哈顿距离最近节点);未命中返回 null(视为自定义坐标)。 */
export function findRegionByCoords(lat: number, lon: number, tolerance = 0.7): ChinaRegionPath | null {
  let best: { path: ChinaRegionPath; d: number; depth: number } | null = null;
  const push = (province: string, city: string | null, leafName: string | null, node: ChinaRegionNode, depth: number): void => {
    const d = Math.abs(node.lat - lat) + Math.abs(node.lon - lon);
    if (d > tolerance) return;
    if (best && !(d < best.d - 1e-9 || (Math.abs(d - best.d) <= 1e-9 && depth > best.depth))) return;
    const path: ChinaRegionPath = { province, city, district: leafName, label: regionLabel(province, city, leafName), lat: node.lat, lon: node.lon };
    best = { path, d, depth };
  };
  for (const province of CHINA_REGIONS) {
    push(province.name, null, null, province, 1);
    for (const city of province.children ?? []) {
      push(province.name, city.name, null, city, 2);
      for (const district of city.children ?? []) {
        push(province.name, city.name, district.name, district, 3);
      }
    }
  }
  const chosen = best as { path: ChinaRegionPath } | null;
  return chosen ? chosen.path : null;
}
