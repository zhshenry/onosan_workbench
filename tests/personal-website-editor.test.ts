import assert from 'node:assert/strict';
import test from 'node:test';
import { createRequire } from 'node:module';
import { mkdtemp, mkdir, readFile, rm, unlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve, sep } from 'node:path';
import { buildSync } from 'esbuild';
import { JSDOM } from 'jsdom';
import { act, createElement } from 'react';
import { PersonalWebsiteContent } from '../electron/personal-website-content';
import type { WebsiteState } from '../shared/personal-website-contracts';

test('editor validates, previews, saves and recovers conflicting drafts against real Markdown files', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'personal-editor-'));
  const file = join(directory, 'src/content/works/data-harness.md');
  await mkdir(join(directory, 'src/content/works'), { recursive: true });
  await writeFile(file, '---\ntitle: Data Harness\ndescription: A real fixture\nyear: 2026\ncategory: product\ncustom: preserved\n---\nOriginal body\n');
  const content = new PersonalWebsiteContent(directory);
  const dom = new JSDOM('<div id="root"></div>', { url: 'http://localhost', pretendToBeVisual: true });
  const globals = ['window', 'document', 'HTMLElement', 'HTMLDialogElement', 'Node', 'navigator', 'localStorage', 'requestAnimationFrame', 'cancelAnimationFrame'] as const;
  const previous = globals.map(name => Object.getOwnPropertyDescriptor(globalThis, name));
  globals.forEach(name => Object.defineProperty(globalThis, name, { configurable: true, value: typeof dom.window[name] === 'function' && name.endsWith('AnimationFrame') ? dom.window[name].bind(dom.window) : dom.window[name] }));
  const previousAct = Object.getOwnPropertyDescriptor(globalThis, 'IS_REACT_ACT_ENVIRONMENT');
  Object.defineProperty(globalThis, 'IS_REACT_ACT_ENVIRONMENT', { configurable: true, value: true });
  dom.window.HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); };
  dom.window.HTMLDialogElement.prototype.close = function () { this.removeAttribute('open'); };
  Object.defineProperty(dom.window.HTMLElement.prototype, 'hidePopover', { value() {} });
  Object.defineProperty(dom.window.HTMLCanvasElement.prototype, 'getContext', { value: () => null });
  const state: WebsiteState = { root: directory, onlineUrl: '', service: { phase: 'stopped', url: '', message: '本地未启动', output: '' }, build: { phase: 'idle', message: '尚未构建', output: '' }, checks: { phase: 'idle', results: [] } };
  const bridge = { start: async () => state, onChanged: () => () => {}, list: () => content.list(), read: (id: string) => content.read(id), save: (input: unknown) => content.save(input), previewSave: (input: unknown) => content.previewSave(input), coverPreview: async () => '' };
  Object.defineProperty(dom.window, 'workbench', { value: { personalWebsite: bridge } });
  const code = buildSync({ entryPoints: ['src/views/PersonalWebsiteView.tsx'], bundle: true, platform: 'node', format: 'cjs', external: ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime', '@phosphor-icons/react'], loader: { '.css': 'empty', '.png': 'dataurl' }, write: false }).outputFiles[0].text;
  const module = { exports: {} as { PersonalWebsiteView: (props: { active: boolean; onPending(): void; onAskAI(): void }) => ReturnType<typeof createElement> } };
  new Function('require', 'module', 'exports', code)(createRequire(import.meta.url), module, module.exports);
  const { createRoot } = await import('react-dom/client');
  let root = createRoot(dom.window.document.getElementById('root')!);
  const query = <T extends HTMLElement = HTMLElement>(selector: string) => dom.window.document.querySelector<T>(selector)!;
  const render = () => act(async () => root.render(createElement(module.exports.PersonalWebsiteView, { active: true, onPending() {}, onAskAI() {} })));
  const waitFor = async (check: () => boolean) => { for (let i = 0; i < 100; i++) { await act(async () => { await new Promise(done => setTimeout(done, 10)); }); if (check()) return; } assert.fail('UI did not reach expected state'); };
  const fill = async (selector: string, value: string) => { const input = query<HTMLInputElement | HTMLTextAreaElement>(selector); await act(async () => { Object.getOwnPropertyDescriptor(input instanceof dom.window.HTMLTextAreaElement ? dom.window.HTMLTextAreaElement.prototype : dom.window.HTMLInputElement.prototype, 'value')!.set!.call(input, value); input.dispatchEvent(new dom.window.Event('input', { bubbles: true })); }); };
  const click = (element: HTMLElement) => act(async () => element.click());
  const submit = () => act(async () => { query('form').dispatchEvent(new dom.window.Event('submit', { bubbles: true, cancelable: true })); });
  t.after(async () => {
    await act(async () => root.unmount()); dom.window.close();
    globals.forEach((name, index) => { if (previous[index]) Object.defineProperty(globalThis, name, previous[index]!); else Reflect.deleteProperty(globalThis, name); });
    if (previousAct) Object.defineProperty(globalThis, 'IS_REACT_ACT_ENVIRONMENT', previousAct); else Reflect.deleteProperty(globalThis, 'IS_REACT_ACT_ENVIRONMENT');
    assert.ok(resolve(directory).startsWith(resolve(tmpdir()) + sep + 'personal-editor-')); await rm(directory, { recursive: true, force: true });
  });
  await render(); await waitFor(() => !!query('#personal-title'));
  assert.equal(query<HTMLButtonElement>('.personal-editor-footer button').disabled, true);
  await fill('#personal-title', ''); await submit();
  assert.equal(query('#personal-title').getAttribute('aria-invalid'), 'true');
  await waitFor(() => dom.window.document.activeElement === query('#personal-title'));
  await fill('#personal-title', 'Edited title'); await fill('#personal-body', 'Edited **Markdown**\n');
  await click(query('.personal-editor-footer button:last-child')); await waitFor(() => !!query('.personal-diff'));
  assert.match(query('.personal-diff').textContent!, /Edited \*\*Markdown\*\*/);
  assert.match(await readFile(file, 'utf8'), /Original body/);
  await click(query('dialog button[aria-label="关闭"]')); await submit();
  await waitFor(() => query('.personal-save-state')?.textContent === '已保存');
  assert.match(await readFile(file, 'utf8'), /Edited \*\*Markdown\*\*/); assert.match(await readFile(file, 'utf8'), /custom: preserved/);
  assert.equal(dom.window.localStorage.getItem('personal-website-draft-v1'), null);

  await writeFile(file, (await readFile(file, 'utf8')) + '\nExternal edit');
  await fill('#personal-body', 'Keep my unsaved draft'); await submit();
  await waitFor(() => !!query('.personal-error'));
  assert.match(query('.personal-error').textContent!, /其他编辑器修改/);
  assert.match(await readFile(file, 'utf8'), /External edit/);
  assert.match(dom.window.localStorage.getItem('personal-website-draft-v1')!, /Keep my unsaved draft/);
  await act(async () => root.unmount()); await unlink(file);
  root = createRoot(dom.window.document.getElementById('root')!); await render();
  await waitFor(() => !!query('#personal-body'));
  assert.equal(query<HTMLTextAreaElement>('#personal-body').value, 'Keep my unsaved draft');
  assert.match(query('.personal-error').textContent!, /草稿已保留/);
  assert.match(dom.window.localStorage.getItem('personal-website-draft-v1')!, /Keep my unsaved draft/);
});
